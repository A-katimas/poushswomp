#include "order.h"

void bubul(T_stack *a, T_stack *b)
{
	int i ;
	i = 0;
	while (a->taille != 0)
	{
		while(i < a->taille)
		{
				if (!(a->data[0] < a->data[1]))
					sa(a);
				ra(a);
				i++;
		}
		pa(a,b);
		i = 0;
	}
}